// 生成赔率
function generateOdds() {
  const homeStr = Math.random() * 3 + 1;
  const awayStr = Math.random() * 3 + 1;
  const total = homeStr + awayStr;
  return {
    spf_win: parseFloat((total / homeStr * (0.8 + Math.random() * 0.4)).toFixed(2)),
    spf_draw: parseFloat((3 + Math.random() * 2).toFixed(2)),
    spf_lose: parseFloat((total / awayStr * (0.8 + Math.random() * 0.4)).toFixed(2)),
    handicap: Math.random() > 0.5 ? (Math.floor(Math.random() * 3) + 0.5) * (Math.random() > 0.5 ? 1 : -1) : (Math.floor(Math.random() * 2) + 0.5) * (Math.random() > 0.5 ? 1 : -1),
    rqspf_win: parseFloat((2 + Math.random() * 2).toFixed(2)),
    rqspf_draw: parseFloat((3 + Math.random() * 1.5).toFixed(2)),
    rqspf_lose: parseFloat((2 + Math.random() * 2).toFixed(2)),
    ou_line: parseFloat([1.5, 2.0, 2.5, 2.5, 3.0, 3.5][Math.floor(Math.random() * 6)].toFixed(1)),
    dxq_over: parseFloat((1.8 + Math.random() * 1.2).toFixed(2)),
    dxq_under: parseFloat((1.8 + Math.random() * 1.2).toFixed(2)),
  };
}

function updateSchedule() {
  console.log('📅 更新2026世界杯真实赛程数据...');

  // 清空现有比赛数据
  const oldMatches = query.all('matches');
  const oldMatchIds = oldMatches.map(m => m.id);

  // 删除关联的投注和交易记录
  console.log(`   清理旧数据: ${oldMatches.length} 场比赛`);
  for (const m of oldMatches) {
    const bets = query.all('bets', { match_id: m.id });
    bets.forEach(b => {
      query.all('transactions', { related_bet_id: b.id }).forEach(t => {
        db.transactions = db.transactions.filter(x => x.id !== t.id);
      });
    });
  }

  // 重置所有表
  const { db } = require('./database');
  db.matches = [];
  db.bets = [];
  db.transactions = [];
  db._nextIds.matches = 1;
  db._nextIds.bets = 1;
  db._nextIds.transactions = 1;

  // 插入小组赛
  let count = 0;
  const now = new Date('2026-06-15');
  for (const [home, away, time, group] of GROUP_MATCHES) {
    const odds = generateOdds();
    const matchDate = new Date(time);
    let status = 'upcoming';
    // 已过期的比赛设为已结束
    if (matchDate < now) {
      status = 'finished';
    }

    query.insert('matches', {
      home_team: home, away_team: away,
      home_flag: TEAMS[home] || '', away_flag: TEAMS[away] || '',
      match_time: time, stage: '小组赛', group_name: group,
      status: status,
      home_score: status === 'finished' ? Math.floor(Math.random() * 4) : null,
      away_score: status === 'finished' ? Math.floor(Math.random() * 3) : null,
      ...odds,
      over_under_line: odds.ou_line,
    });
    count++;
  }

  // 插入淘汰赛
  for (const [stage, time, round] of KNOCKOUT_MATCHES) {
    const odds = generateOdds();
    query.insert('matches', {
      home_team: '待定', away_team: '待定',
      home_flag: '❓', away_flag: '❓',
      match_time: time, stage: round, group_name: null,
      status: 'upcoming',
      home_score: null, away_score: null,
      ...odds,
      over_under_line: odds.ou_line,
    });
    count++;
  }

  saveDB();
  console.log(`   ✅ 已写入 ${count} 场比赛`);
  console.log(`   📊 小组赛: 72场 (A-L组, 48队)`);
  console.log(`   🔥 淘汰赛: 32场 (1/16→1/8→1/4→半决赛→季军赛→决赛)`);
  console.log(`   🏆 合计: 104场`);
  console.log('');
  console.log('🔄 请重启服务器使数据生效');
}

